import assert from 'node:assert/strict';
import { RETIRE_IDS, prepareRetirement } from './retire-owner-expired-20261023.mjs';
import { applyLiveDealEditsToBundle } from './live-deal-edits-lib.mjs';
const now = new Date('2026-10-23T12:00:00Z');
const deals = RETIRE_IDS.map(id => ({id, title: 'Original edited title', validUntil: '2026-10-18', url: 'https://example.org/offer'}));
const keep = {id:'keep', title:'Keep untouched', validUntil:'2026-10-24'};
const bundle = {deals:[keep,...deals],totalDeals:9};
const store = {edits:[{dealId:deals[5].id,title:'Original edited title',hidden:false}]};
const result = prepareRetirement(bundle,store,now);
assert.deepEqual(result.bundle.deals,[keep]);
assert.deepEqual(result.archive.deals,deals);
assert.deepEqual(result.archive.previousEdits,store.edits);
assert.equal(store.edits[0].hidden,false);
assert.equal(result.store.edits.find(e=>e.dealId===deals[5].id).title,store.edits[0].title);
assert.deepEqual(applyLiveDealEditsToBundle(bundle,result.store,{allowManualRemovals:true}).bundle.deals,[keep]);
assert.throws(()=>prepareRetirement({deals:[keep,...deals.slice(1)]},store,now));
assert.throws(()=>prepareRetirement({...bundle,deals:[...bundle.deals,deals[0]]},store,now));
assert.throws(()=>prepareRetirement({...bundle,deals:bundle.deals.map(d=>({...d,validUntil:'2026-10-24'}))},store,now));
console.log('Owner retirement: exact eight, preservation, replay and refusal checks PASS');
