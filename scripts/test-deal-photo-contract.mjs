import assert from 'node:assert/strict';
import {approvedDealPhotoURL, inspectOriginalJPEG, photoDigest} from './deal-photo-contract.mjs';
import {normalizeLiveDealEdit, applyLiveDealEditsToBundle, upsertLiveDealEdit} from './live-deal-edits-lib.mjs';
const url=`https://freefinder.at/assets/approved-deal-photos/${photoDigest('demo').slice(0,16)}-${'a'.repeat(64)}.jpg`;
assert.equal(approvedDealPhotoURL(url,'demo'),url);
for(const raw of [url+'?x=1',url+'#x',url.replace('https:','http:'),url.replace('freefinder.at/','freefinder.at.evil/'),'https://instagram.com/photo.jpg']) assert.equal(approvedDealPhotoURL(raw,'demo'),'');
assert.equal(approvedDealPhotoURL(url,'another'),'');
assert.equal(normalizeLiveDealEdit({dealId:'demo',photoUrl:url}).photoUrl,url);
assert.equal(normalizeLiveDealEdit({dealId:'demo',photoUrl:'https://untrusted.test/photo.jpg'}).photoUrl,'');
let store={edits:[{dealId:'demo',title:'Approved title',hidden:false},{dealId:'hidden',hidden:true}]};
store=upsertLiveDealEdit(store,{dealId:'demo',photoUrl:url});
assert.equal(store.edits.find(e=>e.dealId==='demo').title,'Approved title');
assert.equal(store.edits.find(e=>e.dealId==='hidden').hidden,true);
const feed={deals:[{id:'demo',title:'Raw title',brand:'Cafe',votes:42},{id:'untouched',title:'Other'}]};
const result=applyLiveDealEditsToBundle(feed,store);
assert.equal(result.bundle.deals[0].photoUrl,url);
assert.equal(result.bundle.deals[0].votes,42);
assert.equal(result.bundle.deals[1].title,'Other');
assert.equal(applyLiveDealEditsToBundle(result.bundle, {edits:[{dealId:'demo',photoUrl:''}]}).bundle.deals[0].photoUrl,'');
const jpegHeader = Buffer.from([0xff,0xd8,0xff,0xc0,0,8,8,0x03,0x20,0x04,0xb0,1,0xff,0xd9]);
assert.deepEqual(inspectOriginalJPEG(jpegHeader),{width:1200,height:800});
const exif = Buffer.concat([Buffer.from([0xff,0xd8,0xff,0xe1,0,2]),jpegHeader.subarray(2)]);
assert.throws(()=>inspectOriginalJPEG(exif),/EXIF/);
for(const input of [Buffer.alloc(0),Buffer.from('not an image'),Buffer.alloc(1_500_001)]) assert.throws(()=>inspectOriginalJPEG(input));
console.log('Approved photo URL, per-deal binding, persistent edits and byte limits PASS');
